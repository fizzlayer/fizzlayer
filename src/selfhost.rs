//! Write a Docker Compose `.env` from inside the API image.
//! The host only needs Docker. Random bytes and the service-role JWT are produced here.

use std::{
    fs,
    io::Write,
    path::Path,
    time::{SystemTime, UNIX_EPOCH},
};

use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use ring::{
    hmac,
    rand::{SecureRandom, SystemRandom},
};

const TEN_YEARS_SECS: u64 = 60 * 60 * 24 * 365 * 10;

pub fn init(args: &[String]) -> Result<String, String> {
    let mut out = None;
    let mut force = false;
    let mut iter = args.iter();
    while let Some(arg) = iter.next() {
        match arg.as_str() {
            "--force" => force = true,
            "--out" => {
                let path = iter
                    .next()
                    .ok_or_else(|| "`--out` needs a path.".to_owned())?;
                if path.is_empty() {
                    return Err("`--out` needs a path.".into());
                }
                out = Some(path.clone());
            }
            other if other.starts_with("--out=") => {
                let path = other.trim_start_matches("--out=");
                if path.is_empty() {
                    return Err("`--out` needs a path.".into());
                }
                out = Some(path.to_owned());
            }
            other => {
                return Err(format!(
                    "Unknown argument `{other}`. Use: init [--force] --out PATH"
                ));
            }
        }
    }
    let out = out.ok_or_else(|| "Pass --out PATH, for example --out /out/.env.".to_owned())?;
    write_env(Path::new(&out), force)
}

fn write_env(path: &Path, force: bool) -> Result<String, String> {
    if path.exists() && !force {
        return Err(format!(
            "{} already exists. Pass --force to replace it.",
            path.display()
        ));
    }
    if let Some(parent) = path.parent()
        && !parent.as_os_str().is_empty()
        && !parent.exists()
    {
        return Err(format!("Directory {} does not exist.", parent.display()));
    }
    let rng = SystemRandom::new();
    let postgres_password = random_hex(&rng, 24)?;
    let authenticator_password = random_hex(&rng, 24)?;
    let jwt_secret = random_hex(&rng, 32)?;
    let cron_secret = random_hex(&rng, 32)?;
    let service_role = jwt(&jwt_secret, "service_role")?;
    let anon = jwt(&jwt_secret, "anon")?;
    let text = format!(
        "\
# Generated by fizz-serve init. Do not commit.
COMPOSE_PROFILES=local
PUBLIC_URL=http://localhost:8080
API_PORT=8080
WORKER_PORT=8081
MQTT_PORT=1883
POSTGRES_PASSWORD={postgres_password}
AUTHENTICATOR_PASSWORD={authenticator_password}
JWT_SECRET={jwt_secret}
SUPABASE_SERVICE_ROLE_KEY={service_role}
ANON_KEY={anon}
CRON_SECRET={cron_secret}
SUPABASE_URL=http://gateway:8000
SUPABASE_PUBLIC_URL=http://localhost:8080
FIZZ_ALLOW_INSECURE_HTTP=1
FIZZ_AUTH_UPSTREAM=http://auth:9999
FIZZ_PUBLIC_HOST=localhost:8080
FIZZ_PUBLIC_SCHEME=http
FIZZ_STREAM_URL=http://localhost:8081
FIZZ_MQTT_TCP_URL=mqtt://localhost:1883
MQTT_TCP_PORT=1883
FIZZ_STREAM_ORIGINS=http://localhost:8080
MAILER_AUTOCONFIRM=true
SMTP_ADMIN_EMAIL=admin@localhost
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
SMTP_SENDER_NAME=Fizzlayer
GITHUB_ENABLED=false
GITHUB_CLIENT_ID=
GITHUB_CLIENT_SECRET=
GOOGLE_ENABLED=false
GOOGLE_CLIENT_ID=
GOOGLE_SECRET=
OPENAI_BASE_URL=
OPENAI_API_KEY=
OPENAI_MODEL=
AI_GATEWAY_API_KEY=
AI_GATEWAY_MODEL=
ELEVENLABS_API_KEY=
ELEVENLABS_VOICE_ID=
AGENTPHONE_API_KEY=
AGENTPHONE_AGENT_ID=
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=
STRIPE_PRICE_TINKERER=
STRIPE_PRICE_PRO=
"
    );
    let mut file = {
        let mut options = fs::OpenOptions::new();
        options.write(true).create(true).truncate(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        options
            .open(path)
            .map_err(|error| format!("Could not write {}: {error}", path.display()))?
    };
    file.write_all(text.as_bytes())
        .map_err(|error| format!("Could not write {}: {error}", path.display()))?;
    Ok(path.display().to_string())
}

fn random_hex(rng: &SystemRandom, nbytes: usize) -> Result<String, String> {
    let mut bytes = vec![0u8; nbytes];
    rng.fill(&mut bytes)
        .map_err(|_| "Could not read random bytes.".to_owned())?;
    Ok(encode_hex(&bytes))
}

fn encode_hex(bytes: &[u8]) -> String {
    let mut hex = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        // `fmt::Write` for `String` is infallible.
        let _ = std::fmt::Write::write_fmt(&mut hex, format_args!("{byte:02x}"));
    }
    hex
}

fn jwt(secret: &str, role: &str) -> Result<String, String> {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|_| "System clock is before 1970.".to_owned())?
        .as_secs();
    let iat = now.saturating_sub(60);
    let exp = now.saturating_add(TEN_YEARS_SECS);
    let header = URL_SAFE_NO_PAD.encode(br#"{"alg":"HS256","typ":"JWT"}"#);
    let payload = URL_SAFE_NO_PAD.encode(
        format!(r#"{{"role":"{role}","iss":"supabase","iat":{iat},"exp":{exp}}}"#).as_bytes(),
    );
    let signing = format!("{header}.{payload}");
    let key = hmac::Key::new(hmac::HMAC_SHA256, secret.as_bytes());
    let sig = URL_SAFE_NO_PAD.encode(hmac::sign(&key, signing.as_bytes()).as_ref());
    Ok(format!("{signing}.{sig}"))
}

#[cfg(test)]
mod tests {
    use std::env;

    use super::*;

    #[test]
    fn init_writes_a_service_role_jwt_and_refuses_to_overwrite() {
        let dir = env::temp_dir().join(format!(
            "fizz-init-{}",
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir(&dir).unwrap();
        let path = dir.join(".env");
        let written = init(&["--out".into(), path.to_str().unwrap().to_owned()]).unwrap();
        assert_eq!(written, path.display().to_string());
        let text = fs::read_to_string(&path).unwrap();
        let secret = value(&text, "JWT_SECRET");
        let token = value(&text, "SUPABASE_SERVICE_ROLE_KEY");
        assert_eq!(secret.len(), 64);
        assert!(token.starts_with("eyJ"));
        assert_eq!(token.matches('.').count(), 2);
        verify(&secret, &token);
        let again = init(&["--out".into(), path.to_str().unwrap().to_owned()]);
        assert!(again.unwrap_err().contains("--force"));
        let _ = fs::remove_dir_all(&dir);
    }

    fn value(text: &str, key: &str) -> String {
        text.lines()
            .find_map(|line| line.strip_prefix(&format!("{key}=")))
            .unwrap()
            .to_owned()
    }

    fn verify(secret: &str, token: &str) {
        let (signing, sig) = token.rsplit_once('.').unwrap();
        let key = hmac::Key::new(hmac::HMAC_SHA256, secret.as_bytes());
        hmac::verify(
            &key,
            signing.as_bytes(),
            &URL_SAFE_NO_PAD.decode(sig).unwrap(),
        )
        .unwrap();
        let payload = signing.split('.').nth(1).unwrap();
        let json = URL_SAFE_NO_PAD.decode(payload).unwrap();
        let json = String::from_utf8(json).unwrap();
        assert!(json.contains(r#""role":"service_role""#));
    }
}
