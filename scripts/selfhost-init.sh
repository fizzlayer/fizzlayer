#!/bin/sh
# Write a secret .env for Docker Compose. Re-run with --force to replace it.
# Inside a checkout this writes deploy/.env. Downloaded on its own, or piped
# to sh, it writes .env in the current directory next to compose.yml.
set -eu
script_dir=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/.." && pwd)
if [ -f "$repo_root/deploy/docker-compose.yml" ] && [ -f "$repo_root/scripts/selfhost-init.sh" ]; then
  out="$repo_root/deploy/.env"
else
  out="$(pwd)/.env"
fi
if [ -f "$out" ] && [ "${1:-}" != "--force" ]; then
  echo "$out already exists. Pass --force to replace it." >&2
  exit 1
fi
postgres_password=$(openssl rand -hex 24)
authenticator_password=$(openssl rand -hex 24)
jwt_secret=$(openssl rand -hex 32)
cron_secret=$(openssl rand -hex 32)
export POSTGRES_PASSWORD="$postgres_password"
export AUTHENTICATOR_PASSWORD="$authenticator_password"
export JWT_SECRET="$jwt_secret"
export CRON_SECRET="$cron_secret"
export OUT="$out"
python3 - <<'PY'
import hmac, hashlib, base64, json, os, time

def b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()

def jwt(secret: str, role: str) -> str:
    header = b64(json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode())
    payload = b64(json.dumps({
        "role": role,
        "iss": "supabase",
        "iat": int(time.time()) - 60,
        "exp": int(time.time()) + 60 * 60 * 24 * 365 * 10,
    }, separators=(",", ":")).encode())
    signing = f"{header}.{payload}".encode()
    sig = hmac.new(secret.encode(), signing, hashlib.sha256).digest()
    return f"{header}.{payload}.{b64(sig)}"

secret = os.environ["JWT_SECRET"]
text = f"""# Generated by scripts/selfhost-init.sh. Do not commit.
COMPOSE_PROFILES=local
PUBLIC_URL=http://localhost:8080
API_PORT=8080
WORKER_PORT=8081
MQTT_PORT=1883
POSTGRES_PASSWORD={os.environ["POSTGRES_PASSWORD"]}
AUTHENTICATOR_PASSWORD={os.environ["AUTHENTICATOR_PASSWORD"]}
JWT_SECRET={secret}
SUPABASE_SERVICE_ROLE_KEY={jwt(secret, "service_role")}
ANON_KEY={jwt(secret, "anon")}
CRON_SECRET={os.environ["CRON_SECRET"]}
SUPABASE_URL=http://gateway:8000
SUPABASE_PUBLIC_URL=http://localhost:8080
FIZZ_ALLOW_INSECURE_HTTP=1
FIZZ_AUTH_UPSTREAM=http://auth:9999
FIZZ_PUBLIC_HOST=localhost:8080
FIZZ_PUBLIC_SCHEME=http
FIZZ_STREAM_URL=http://localhost:8081
FIZZ_MQTT_TCP_URL=mqtt://localhost:1883
MQTT_TCP_PORT=1883
FIZZ_STREAM_ORIGINS=http://localhost:8080
MAILER_AUTOCONFIRM=true
SMTP_ADMIN_EMAIL=admin@localhost
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
SMTP_SENDER_NAME=Fizzlayer
GITHUB_ENABLED=false
GITHUB_CLIENT_ID=
GITHUB_CLIENT_SECRET=
GOOGLE_ENABLED=false
GOOGLE_CLIENT_ID=
GOOGLE_SECRET=
OPENAI_BASE_URL=
OPENAI_API_KEY=
OPENAI_MODEL=
AI_GATEWAY_API_KEY=
AI_GATEWAY_MODEL=
ELEVENLABS_API_KEY=
ELEVENLABS_VOICE_ID=
AGENTPHONE_API_KEY=
AGENTPHONE_AGENT_ID=
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=
STRIPE_PRICE_TINKERER=
STRIPE_PRICE_PRO=
"""
path = os.environ["OUT"]
with open(path, "w", encoding="utf-8") as handle:
    handle.write(text)
os.chmod(path, 0o600)
PY
echo "Wrote $out"
